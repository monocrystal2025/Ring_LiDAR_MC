classdef mcRoiBlockSizeTest < matlab.unittest.TestCase
    %mcRoiBlockSizeTest Tests for the ROI pulse-block selection policy.

    properties (TestParameter)
        blockCase = struct( ...
            'ringAt10', {{10e-3, 'ring', 30000}}, ...
            'ringAbove10', {{15e-3, 'ring', 2000}}, ...
            'ringAt50', {{50e-3, 'ring', 2000}}, ...
            'ringAbove50', {{55e-3, 'ring', 2000}}, ...
            'ringAt150', {{150e-3, 'ring', 2000}}, ...
            'ringAbove150', {{155e-3, 'ring', 5000}}, ...
            'ringAt250', {{250e-3, 'ring', 5000}}, ...
            'ringAbove250', {{255e-3, 'ring', 5000}}, ...
            'lineAt10', {{10e-3, 'line', 30000}}, ...
            'lineAbove10', {{15e-3, 'line', 2000}}, ...
            'lineAt50', {{50e-3, 'line', 2000}}, ...
            'lineAbove50', {{55e-3, 'line', 2000}}, ...
            'lineAt150', {{150e-3, 'line', 2000}}, ...
            'lineAbove150', {{155e-3, 'line', 5000}}, ...
            'lineAt250', {{250e-3, 'line', 5000}}, ...
            'lineAbove250', {{255e-3, 'line', 5000}}, ...
            'pointAt10', {{10e-3, 'point', 20000}}, ...
            'pointAbove10', {{15e-3, 'point', 2000}}, ...
            'pointAt50', {{50e-3, 'point', 2000}}, ...
            'pointAbove50', {{55e-3, 'point', 10000}}, ...
            'pointAt150', {{150e-3, 'point', 10000}}, ...
            'pointAbove150', {{155e-3, 'point', 10000}}, ...
            'pointAt250', {{250e-3, 'point', 10000}}, ...
            'pointAbove250', {{255e-3, 'point', 5000}})
    end

    methods (TestClassSetup)
        function addProjectFolder(testCase)
            projectFolder = fileparts(fileparts(mfilename('fullpath')));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                projectFolder));
        end
    end

    methods (Test)
        function testMeasuredMapping(testCase, blockCase)
            actual = mc_roi_block_size(blockCase{1}, blockCase{2});

            testCase.verifyEqual(actual, blockCase{3});
        end

        function testRejectsNonpositiveAngle(testCase)
            testCase.verifyError(@() mc_roi_block_size(0, 'point'), ...
                'MATLAB:mc_roi_block_size:expectedPositive');
        end
    end
end
